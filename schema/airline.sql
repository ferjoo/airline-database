--------------------------------------------------------------------------------
-- Airline operations database
-- Relational model for an airline's control system: airports, fleet,
-- maintenance, flights and their daily operations, crew, reservations,
-- baggage, and operational events.
--
-- Target  : Oracle Database 23ai (any version 12c or later works)
-- File    : schema/airline.sql
-- Objects : 29 tables, 36 foreign keys, 39 check constraints
--
-- IMPORT INTO ORACLE SQL DATA MODELER
--   File > Import > DDL File, source "Oracle Database 12c or later".
--   Expected result: 29 tables.
--   Then right-click Relational_1 > Engineer to Logical Model.
--
-- This file has no anonymous PL/SQL blocks and no CREATE INDEX statements,
-- because the Data Modeler DDL parser can stop on them.
--
-- DESIGN NOTE: the model uses composite natural keys so the diagram shows the
-- identity dependencies of the entity-relationship model (OPERACION_VUELO and
-- SEGMENTO are weak entities). In a physical implementation it would be
-- reasonable to replace them with surrogate keys and keep the natural key as a
-- UNIQUE constraint; see the README for the trade-off.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- BLOCK 1. AIRPORTS AND INFRASTRUCTURE
--------------------------------------------------------------------------------

-- The 3-letter IATA code is the airport's unique key.
CREATE TABLE AEROPUERTO (
  COD_IATA  CHAR(3)       NOT NULL,
  NOMBRE    VARCHAR2(120) NOT NULL,
  CIUDAD    VARCHAR2(80)  NOT NULL,
  PAIS      VARCHAR2(80)  NOT NULL,
  CONSTRAINT PK_AEROPUERTO   PRIMARY KEY (COD_IATA),
  CONSTRAINT CK_AEROPUERTO_IATA CHECK (REGEXP_LIKE(COD_IATA, '^[A-Z]{3}$'))
);

-- Weak entity: a terminal id is only unique within its airport.
CREATE TABLE TERMINAL (
  COD_IATA     CHAR(3)      NOT NULL,
  ID_TERMINAL  VARCHAR2(10) NOT NULL,
  NOMBRE       VARCHAR2(80),
  CONSTRAINT PK_TERMINAL            PRIMARY KEY (COD_IATA, ID_TERMINAL),
  CONSTRAINT FK_TERMINAL_AEROPUERTO FOREIGN KEY (COD_IATA) REFERENCES AEROPUERTO (COD_IATA)
);

-- Weak entity of TERMINAL.
CREATE TABLE GATE (
  COD_IATA     CHAR(3)      NOT NULL,
  ID_TERMINAL  VARCHAR2(10) NOT NULL,
  ID_GATE      VARCHAR2(10) NOT NULL,
  TIPO         VARCHAR2(20) NOT NULL,
  CONSTRAINT PK_GATE          PRIMARY KEY (COD_IATA, ID_TERMINAL, ID_GATE),
  CONSTRAINT FK_GATE_TERMINAL FOREIGN KEY (COD_IATA, ID_TERMINAL)
             REFERENCES TERMINAL (COD_IATA, ID_TERMINAL),
  CONSTRAINT CK_GATE_TIPO     CHECK (TIPO IN ('INTERNACIONAL','DOMESTICO','MIXTO'))
);

-- Runways carry their length, used by the minimum-runway-length rule.
CREATE TABLE RUNWAY (
  COD_IATA         CHAR(3)      NOT NULL,
  ID_PISTA         VARCHAR2(10) NOT NULL,
  LONGITUD_M       NUMBER(6)    NOT NULL,
  TIPO_SUPERFICIE  VARCHAR2(30) NOT NULL,
  CONSTRAINT PK_RUNWAY            PRIMARY KEY (COD_IATA, ID_PISTA),
  CONSTRAINT FK_RUNWAY_AEROPUERTO FOREIGN KEY (COD_IATA) REFERENCES AEROPUERTO (COD_IATA),
  CONSTRAINT CK_RUNWAY_LONGITUD   CHECK (LONGITUD_M > 0)
);


--------------------------------------------------------------------------------
-- BLOCK 2. FLEET, AIRCRAFT AND MAINTENANCE
--------------------------------------------------------------------------------

CREATE TABLE FLOTA (
  ID_FLOTA     NUMBER(10)   NOT NULL,
  NOMBRE       VARCHAR2(80) NOT NULL,
  DESCRIPCION  VARCHAR2(200),
  CONSTRAINT PK_FLOTA        PRIMARY KEY (ID_FLOTA),
  CONSTRAINT UQ_FLOTA_NOMBRE UNIQUE (NOMBRE)
);

-- The model is split from the aircraft because two rules depend on it: crew
-- qualifications are granted per model, and the minimum runway length is a
-- property of the model.
CREATE TABLE MODELO_AERONAVE (
  ID_MODELO                 VARCHAR2(30) NOT NULL,
  FABRICANTE                VARCHAR2(60) NOT NULL,
  TIPO                      VARCHAR2(20) NOT NULL,
  LONGITUD_PISTA_MINIMA_M   NUMBER(6)    NOT NULL,
  CONSTRAINT PK_MODELO_AERONAVE   PRIMARY KEY (ID_MODELO),
  CONSTRAINT CK_MODELO_TIPO       CHECK (TIPO IN ('NARROW-BODY','WIDE-BODY','REGIONAL')),
  CONSTRAINT CK_MODELO_PISTA      CHECK (LONGITUD_PISTA_MINIMA_M > 0)
);

-- Unique registration; every aircraft belongs to a fleet.
CREATE TABLE AERONAVE (
  MATRICULA               VARCHAR2(12) NOT NULL,
  ID_MODELO               VARCHAR2(30) NOT NULL,
  ID_FLOTA                NUMBER(10)   NOT NULL,
  CAPACIDAD_TOTAL_PLAZAS  NUMBER(5)    NOT NULL,
  ESTADO                  VARCHAR2(25) NOT NULL,
  CONSTRAINT PK_AERONAVE         PRIMARY KEY (MATRICULA),
  CONSTRAINT FK_AERONAVE_MODELO  FOREIGN KEY (ID_MODELO) REFERENCES MODELO_AERONAVE (ID_MODELO),
  CONSTRAINT FK_AERONAVE_FLOTA   FOREIGN KEY (ID_FLOTA)  REFERENCES FLOTA (ID_FLOTA),
  CONSTRAINT CK_AERONAVE_ESTADO  CHECK (ESTADO IN ('EN SERVICIO','FUERA DE SERVICIO')),
  CONSTRAINT CK_AERONAVE_PLAZAS  CHECK (CAPACIDAD_TOTAL_PLAZAS > 0)
);

CREATE TABLE TALLER (
  ID_TALLER  NUMBER(10)    NOT NULL,
  NOMBRE     VARCHAR2(100) NOT NULL,
  UBICACION  VARCHAR2(120),
  CONSTRAINT PK_TALLER PRIMARY KEY (ID_TALLER)
);

-- Maintenance history. Weak entity: an aircraft cannot have two maintenance
-- jobs that start on the same day.
CREATE TABLE MANTENIMIENTO (
  MATRICULA           VARCHAR2(12) NOT NULL,
  FECHA_INICIO        DATE         NOT NULL,
  FECHA_FIN           DATE,
  TIPO_MANTENIMIENTO  VARCHAR2(30) NOT NULL,
  ID_TALLER           NUMBER(10)   NOT NULL,
  CONSTRAINT PK_MANTENIMIENTO          PRIMARY KEY (MATRICULA, FECHA_INICIO),
  CONSTRAINT FK_MANTENIMIENTO_AERONAVE FOREIGN KEY (MATRICULA) REFERENCES AERONAVE (MATRICULA),
  CONSTRAINT FK_MANTENIMIENTO_TALLER   FOREIGN KEY (ID_TALLER) REFERENCES TALLER (ID_TALLER),
  CONSTRAINT CK_MANTENIMIENTO_FECHAS   CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_MANTENIMIENTO_TIPO     CHECK (TIPO_MANTENIMIENTO IN ('PREVENTIVO','CORRECTIVO','MAYOR'))
);

-- A seat belongs to one aircraft and one specific cabin class.
CREATE TABLE BUTACA (
  MATRICULA   VARCHAR2(12) NOT NULL,
  NUM_BUTACA  VARCHAR2(6)  NOT NULL,
  CLASE       VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_BUTACA          PRIMARY KEY (MATRICULA, NUM_BUTACA),
  CONSTRAINT FK_BUTACA_AERONAVE FOREIGN KEY (MATRICULA) REFERENCES AERONAVE (MATRICULA),
  CONSTRAINT CK_BUTACA_CLASE    CHECK (CLASE IN ('ECONOMICA','BUSINESS','FIRST'))
);


--------------------------------------------------------------------------------
-- BLOCK 3. FLIGHTS, OPERATIONS AND SEGMENTS
--------------------------------------------------------------------------------

CREATE TABLE AEROLINEA (
  COD_AEROLINEA  VARCHAR2(3)   NOT NULL,
  NOMBRE         VARCHAR2(100) NOT NULL,
  PAIS           VARCHAR2(80),
  CONSTRAINT PK_AEROLINEA        PRIMARY KEY (COD_AEROLINEA),
  CONSTRAINT UQ_AEROLINEA_NOMBRE UNIQUE (NOMBRE)
);

-- VUELO is the COMMERCIAL concept. Its number (AA123) repeats every day, so on
-- its own it does not identify an operation.
CREATE TABLE VUELO (
  NUM_VUELO              VARCHAR2(10) NOT NULL,
  COD_AEROLINEA          VARCHAR2(3)  NOT NULL,
  DURACION_ESTIMADA_MIN  NUMBER(5),
  CONSTRAINT PK_VUELO           PRIMARY KEY (NUM_VUELO),
  CONSTRAINT FK_VUELO_AEROLINEA FOREIGN KEY (COD_AEROLINEA) REFERENCES AEROLINEA (COD_AEROLINEA),
  CONSTRAINT CK_VUELO_DURACION  CHECK (DURACION_ESTIMADA_MIN IS NULL OR DURACION_ESTIMADA_MIN > 0)
);

-- CENTRAL DECISION OF THE MODEL:
-- An operation is identified by NUM_VUELO + FECHA_OPERACION. AA123 on
-- September 15 and AA123 on September 16 are different events, with different
-- crew, aircraft, gates and delays. Weak entity of VUELO.
CREATE TABLE OPERACION_VUELO (
  NUM_VUELO         VARCHAR2(10) NOT NULL,
  FECHA_OPERACION   DATE         NOT NULL,
  ESTADO_OPERATIVO  VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_OPERACION_VUELO       PRIMARY KEY (NUM_VUELO, FECHA_OPERACION),
  CONSTRAINT FK_OPERACION_VUELO       FOREIGN KEY (NUM_VUELO) REFERENCES VUELO (NUM_VUELO),
  CONSTRAINT CK_OPERACION_ESTADO      CHECK (ESTADO_OPERATIVO IN ('PROGRAMADO','EN VUELO','ATERRIZADO','CANCELADO'))
);

-- NUM_SECUENCIA keeps the order of the legs and, being part of the key,
-- prevents duplicate segments.
--
-- The gate foreign keys include the airport code, so it is guaranteed
-- DECLARATIVELY that the departure gate belongs to the origin airport and the
-- arrival gate to the destination airport.
CREATE TABLE SEGMENTO (
  NUM_VUELO            VARCHAR2(10) NOT NULL,
  FECHA_OPERACION      DATE         NOT NULL,
  NUM_SECUENCIA        NUMBER(2)    NOT NULL,
  AEROPUERTO_ORIGEN    CHAR(3)      NOT NULL,
  AEROPUERTO_DESTINO   CHAR(3)      NOT NULL,
  TERMINAL_SALIDA      VARCHAR2(10),
  GATE_SALIDA          VARCHAR2(10),
  TERMINAL_LLEGADA     VARCHAR2(10),
  GATE_LLEGADA         VARCHAR2(10),
  SALIDA_PROGRAMADA    DATE         NOT NULL,
  LLEGADA_PROGRAMADA   DATE         NOT NULL,
  SALIDA_REAL          DATE,
  LLEGADA_REAL         DATE,
  MATRICULA            VARCHAR2(12),
  RETRASO_SALIDA_MIN   NUMBER(7)
    GENERATED ALWAYS AS (ROUND((SALIDA_REAL - SALIDA_PROGRAMADA) * 1440)) VIRTUAL,
  CONSTRAINT PK_SEGMENTO             PRIMARY KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA),
  CONSTRAINT FK_SEGMENTO_OPERACION   FOREIGN KEY (NUM_VUELO, FECHA_OPERACION)
             REFERENCES OPERACION_VUELO (NUM_VUELO, FECHA_OPERACION),
  CONSTRAINT FK_SEGMENTO_ORIGEN      FOREIGN KEY (AEROPUERTO_ORIGEN)  REFERENCES AEROPUERTO (COD_IATA),
  CONSTRAINT FK_SEGMENTO_DESTINO     FOREIGN KEY (AEROPUERTO_DESTINO) REFERENCES AEROPUERTO (COD_IATA),
  CONSTRAINT FK_SEGMENTO_GATE_SAL    FOREIGN KEY (AEROPUERTO_ORIGEN, TERMINAL_SALIDA, GATE_SALIDA)
             REFERENCES GATE (COD_IATA, ID_TERMINAL, ID_GATE),
  CONSTRAINT FK_SEGMENTO_GATE_LLE    FOREIGN KEY (AEROPUERTO_DESTINO, TERMINAL_LLEGADA, GATE_LLEGADA)
             REFERENCES GATE (COD_IATA, ID_TERMINAL, ID_GATE),
  CONSTRAINT FK_SEGMENTO_AERONAVE    FOREIGN KEY (MATRICULA) REFERENCES AERONAVE (MATRICULA),
  CONSTRAINT CK_SEGMENTO_DISTINTOS   CHECK (AEROPUERTO_ORIGEN <> AEROPUERTO_DESTINO),
  CONSTRAINT CK_SEGMENTO_SECUENCIA   CHECK (NUM_SECUENCIA > 0),
  CONSTRAINT CK_SEGMENTO_HORARIO     CHECK (LLEGADA_PROGRAMADA > SALIDA_PROGRAMADA)
);

-- Seat inventory per segment and cabin class.
CREATE TABLE INVENTARIO_PLAZAS (
  NUM_VUELO           VARCHAR2(10) NOT NULL,
  FECHA_OPERACION     DATE         NOT NULL,
  NUM_SECUENCIA       NUMBER(2)    NOT NULL,
  CLASE               VARCHAR2(15) NOT NULL,
  PLAZAS_TOTALES      NUMBER(5)    NOT NULL,
  PLAZAS_OCUPADAS     NUMBER(5)    DEFAULT 0 NOT NULL,
  PLAZAS_DISPONIBLES  NUMBER(5)
    GENERATED ALWAYS AS (PLAZAS_TOTALES - PLAZAS_OCUPADAS) VIRTUAL,
  CONSTRAINT PK_INVENTARIO_PLAZAS  PRIMARY KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA, CLASE),
  CONSTRAINT FK_INVENTARIO_SEGMENTO FOREIGN KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA)
             REFERENCES SEGMENTO (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA),
  CONSTRAINT CK_INVENTARIO_CLASE   CHECK (CLASE IN ('ECONOMICA','BUSINESS','FIRST')),
  CONSTRAINT CK_INVENTARIO_TOTALES CHECK (PLAZAS_TOTALES >= 0),
  CONSTRAINT CK_INVENTARIO_OCUPADAS CHECK (PLAZAS_OCUPADAS BETWEEN 0 AND PLAZAS_TOTALES)
);


--------------------------------------------------------------------------------
-- BLOCK 4. CREW
--------------------------------------------------------------------------------

-- Supertype. UQ_TRIPULANTE_TIPO is not a business rule: it lets the subtypes
-- declare a composite foreign key, which guarantees that a PILOTO row can only
-- point to a crew member whose type is pilot.
CREATE TABLE TRIPULANTE (
  ID_TRIPULANTE     NUMBER(10)    NOT NULL,
  NOMBRE_COMPLETO   VARCHAR2(120) NOT NULL,
  FECHA_NACIMIENTO  DATE          NOT NULL,
  RANGO_PUESTO      VARCHAR2(40)  NOT NULL,
  AEROPUERTO_BASE   CHAR(3)       NOT NULL,
  TIPO              VARCHAR2(10)  NOT NULL,
  CONSTRAINT PK_TRIPULANTE       PRIMARY KEY (ID_TRIPULANTE),
  CONSTRAINT FK_TRIPULANTE_BASE  FOREIGN KEY (AEROPUERTO_BASE) REFERENCES AEROPUERTO (COD_IATA),
  CONSTRAINT UQ_TRIPULANTE_TIPO  UNIQUE (ID_TRIPULANTE, TIPO),
  CONSTRAINT CK_TRIPULANTE_TIPO  CHECK (TIPO IN ('PILOTO','CABINA'))
);

-- Subtype. Only pilots hold a license.
CREATE TABLE PILOTO (
  ID_TRIPULANTE  NUMBER(10)   NOT NULL,
  TIPO           VARCHAR2(10) DEFAULT 'PILOTO' NOT NULL,
  NUM_LICENCIA   VARCHAR2(30) NOT NULL,
  TIPO_LICENCIA  VARCHAR2(20) NOT NULL,
  HORAS_VUELO    NUMBER(7)    DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PILOTO            PRIMARY KEY (ID_TRIPULANTE),
  CONSTRAINT FK_PILOTO_TRIPULANTE FOREIGN KEY (ID_TRIPULANTE, TIPO)
             REFERENCES TRIPULANTE (ID_TRIPULANTE, TIPO),
  CONSTRAINT UQ_PILOTO_LICENCIA   UNIQUE (NUM_LICENCIA),
  CONSTRAINT CK_PILOTO_TIPO       CHECK (TIPO = 'PILOTO'),
  CONSTRAINT CK_PILOTO_HORAS      CHECK (HORAS_VUELO >= 0)
);

-- Subtype, disjoint from the previous one.
CREATE TABLE TRIPULANTE_CABINA (
  ID_TRIPULANTE            NUMBER(10)   NOT NULL,
  TIPO                     VARCHAR2(10) DEFAULT 'CABINA' NOT NULL,
  CERTIFICACION_SEGURIDAD  VARCHAR2(40) NOT NULL,
  IDIOMAS                  VARCHAR2(120),
  CONSTRAINT PK_TRIPULANTE_CABINA      PRIMARY KEY (ID_TRIPULANTE),
  CONSTRAINT FK_CABINA_TRIPULANTE      FOREIGN KEY (ID_TRIPULANTE, TIPO)
             REFERENCES TRIPULANTE (ID_TRIPULANTE, TIPO),
  CONSTRAINT CK_CABINA_TIPO            CHECK (TIPO = 'CABINA')
);

-- "Aircraft qualifications" was a multivalued attribute. It is resolved as an
-- associative entity, which also gains attributes of its own.
CREATE TABLE CALIFICACION (
  ID_TRIPULANTE      NUMBER(10)   NOT NULL,
  ID_MODELO          VARCHAR2(30) NOT NULL,
  FECHA_OBTENCION    DATE         NOT NULL,
  FECHA_VENCIMIENTO  DATE,
  CONSTRAINT PK_CALIFICACION            PRIMARY KEY (ID_TRIPULANTE, ID_MODELO),
  CONSTRAINT FK_CALIFICACION_TRIPULANTE FOREIGN KEY (ID_TRIPULANTE) REFERENCES TRIPULANTE (ID_TRIPULANTE),
  CONSTRAINT FK_CALIFICACION_MODELO     FOREIGN KEY (ID_MODELO) REFERENCES MODELO_AERONAVE (ID_MODELO),
  CONSTRAINT CK_CALIFICACION_FECHAS     CHECK (FECHA_VENCIMIENTO IS NULL OR FECHA_VENCIMIENTO > FECHA_OBTENCION)
);

-- Assignment history per segment and role.
-- The role is an attribute of the RELATIONSHIP: the same person can be captain
-- on one segment and first officer on another.
CREATE TABLE ASIGNACION_TRIPULACION (
  NUM_VUELO         VARCHAR2(10) NOT NULL,
  FECHA_OPERACION   DATE         NOT NULL,
  NUM_SECUENCIA     NUMBER(2)    NOT NULL,
  ID_TRIPULANTE     NUMBER(10)   NOT NULL,
  ROL               VARCHAR2(20) NOT NULL,
  FECHA_ASIGNACION  DATE         NOT NULL,
  CONSTRAINT PK_ASIGNACION_TRIPULACION PRIMARY KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA, ID_TRIPULANTE),
  CONSTRAINT FK_ASIGNACION_SEGMENTO    FOREIGN KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA)
             REFERENCES SEGMENTO (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA),
  CONSTRAINT FK_ASIGNACION_TRIPULANTE  FOREIGN KEY (ID_TRIPULANTE) REFERENCES TRIPULANTE (ID_TRIPULANTE),
  CONSTRAINT CK_ASIGNACION_ROL         CHECK (ROL IN ('COMANDANTE','COPILOTO','JEFE DE CABINA','AUXILIAR'))
);


--------------------------------------------------------------------------------
-- BLOCK 5. RESERVATIONS, CONNECTIONS AND BAGGAGE
--------------------------------------------------------------------------------

CREATE TABLE PASAJERO (
  ID_PASAJERO          NUMBER(10)    NOT NULL,
  NOMBRE_COMPLETO      VARCHAR2(120) NOT NULL,
  DOCUMENTO_IDENTIDAD  VARCHAR2(30)  NOT NULL,
  FECHA_NACIMIENTO     DATE          NOT NULL,
  CONSTRAINT PK_PASAJERO           PRIMARY KEY (ID_PASAJERO),
  CONSTRAINT UQ_PASAJERO_DOCUMENTO UNIQUE (DOCUMENTO_IDENTIDAD)
);

-- Booking record (PNR) with a unique code.
CREATE TABLE RESERVA (
  COD_PNR        VARCHAR2(8)  NOT NULL,
  FECHA_RESERVA  DATE         NOT NULL,
  ESTADO         VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_RESERVA        PRIMARY KEY (COD_PNR),
  CONSTRAINT CK_RESERVA_ESTADO CHECK (ESTADO IN ('CONFIRMADA','CANCELADA','VOLADA'))
);

-- One PNR can cover several passengers: many-to-many relationship.
CREATE TABLE RESERVA_PASAJERO (
  COD_PNR      VARCHAR2(8) NOT NULL,
  ID_PASAJERO  NUMBER(10)  NOT NULL,
  CONSTRAINT PK_RESERVA_PASAJERO       PRIMARY KEY (COD_PNR, ID_PASAJERO),
  CONSTRAINT FK_RESPAS_RESERVA         FOREIGN KEY (COD_PNR) REFERENCES RESERVA (COD_PNR),
  CONSTRAINT FK_RESPAS_PASAJERO        FOREIGN KEY (ID_PASAJERO) REFERENCES PASAJERO (ID_PASAJERO)
);

-- The itinerary. ROL_DESTINO lets the same segment be the final destination
-- for one passenger and an intermediate stop for another.
-- UQ_RESSEG_ORDEN lets CONEXION reference two legs of the itinerary by their
-- position.
CREATE TABLE RESERVA_SEGMENTO (
  COD_PNR           VARCHAR2(8)  NOT NULL,
  NUM_VUELO         VARCHAR2(10) NOT NULL,
  FECHA_OPERACION   DATE         NOT NULL,
  NUM_SECUENCIA     NUMBER(2)    NOT NULL,
  ORDEN_ITINERARIO  NUMBER(2)    NOT NULL,
  CLASE             VARCHAR2(15) NOT NULL,
  MATRICULA_BUTACA  VARCHAR2(12),
  NUM_BUTACA        VARCHAR2(6),
  ROL_DESTINO       VARCHAR2(12) NOT NULL,
  CONSTRAINT PK_RESERVA_SEGMENTO  PRIMARY KEY (COD_PNR, NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA),
  CONSTRAINT FK_RESSEG_RESERVA    FOREIGN KEY (COD_PNR) REFERENCES RESERVA (COD_PNR),
  CONSTRAINT FK_RESSEG_SEGMENTO   FOREIGN KEY (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA)
             REFERENCES SEGMENTO (NUM_VUELO, FECHA_OPERACION, NUM_SECUENCIA),
  CONSTRAINT FK_RESSEG_BUTACA     FOREIGN KEY (MATRICULA_BUTACA, NUM_BUTACA)
             REFERENCES BUTACA (MATRICULA, NUM_BUTACA),
  CONSTRAINT UQ_RESSEG_ORDEN      UNIQUE (COD_PNR, ORDEN_ITINERARIO),
  CONSTRAINT CK_RESSEG_CLASE      CHECK (CLASE IN ('ECONOMICA','BUSINESS','FIRST')),
  CONSTRAINT CK_RESSEG_DESTINO    CHECK (ROL_DESTINO IN ('INTERMEDIO','FINAL')),
  CONSTRAINT CK_RESSEG_ORDEN      CHECK (ORDEN_ITINERARIO > 0)
);

-- A connection links TWO CONSECUTIVE LEGS of the same itinerary, which is why
-- it hangs from RESERVA_SEGMENTO and not from the segment.
CREATE TABLE CONEXION (
  COD_PNR                   VARCHAR2(8) NOT NULL,
  ORDEN_ITINERARIO_LLEGADA  NUMBER(2)   NOT NULL,
  ORDEN_ITINERARIO_SALIDA   NUMBER(2)   NOT NULL,
  TIEMPO_MINIMO_MIN         NUMBER(5)   NOT NULL,
  TIEMPO_REAL_MIN           NUMBER(5),
  ES_MISCONNECTED           NUMBER(1)
    GENERATED ALWAYS AS (CASE WHEN TIEMPO_REAL_MIN IS NULL THEN NULL
                              WHEN TIEMPO_REAL_MIN < TIEMPO_MINIMO_MIN THEN 1
                              ELSE 0 END) VIRTUAL,
  CONSTRAINT PK_CONEXION           PRIMARY KEY (COD_PNR, ORDEN_ITINERARIO_LLEGADA, ORDEN_ITINERARIO_SALIDA),
  CONSTRAINT FK_CONEXION_LLEGADA   FOREIGN KEY (COD_PNR, ORDEN_ITINERARIO_LLEGADA)
             REFERENCES RESERVA_SEGMENTO (COD_PNR, ORDEN_ITINERARIO),
  CONSTRAINT FK_CONEXION_SALIDA    FOREIGN KEY (COD_PNR, ORDEN_ITINERARIO_SALIDA)
             REFERENCES RESERVA_SEGMENTO (COD_PNR, ORDEN_ITINERARIO),
  CONSTRAINT CK_CONEXION_CONSECUTIVA CHECK (ORDEN_ITINERARIO_SALIDA = ORDEN_ITINERARIO_LLEGADA + 1),
  CONSTRAINT CK_CONEXION_MINIMO      CHECK (TIEMPO_MINIMO_MIN > 0)
);

-- Checked baggage pieces.
CREATE TABLE EQUIPAJE (
  ID_EQUIPAJE  NUMBER(10)   NOT NULL,
  COD_PNR      VARCHAR2(8)  NOT NULL,
  NUM_PIEZA    NUMBER(3)    NOT NULL,
  PESO_KG      NUMBER(6,2)  NOT NULL,
  TIPO         VARCHAR2(20) NOT NULL,
  ESTADO       VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_EQUIPAJE        PRIMARY KEY (ID_EQUIPAJE),
  CONSTRAINT FK_EQUIPAJE_RESERVA FOREIGN KEY (COD_PNR) REFERENCES RESERVA (COD_PNR),
  CONSTRAINT UQ_EQUIPAJE_PIEZA  UNIQUE (COD_PNR, NUM_PIEZA),
  CONSTRAINT CK_EQUIPAJE_TIPO   CHECK (TIPO IN ('NORMAL','SOBREDIMENSIONADO')),
  CONSTRAINT CK_EQUIPAJE_ESTADO CHECK (ESTADO IN ('FACTURADO','ENTREGADO','PERDIDO','DANADO')),
  CONSTRAINT CK_EQUIPAJE_PESO   CHECK (PESO_KG > 0)
);

-- Baggage claim history.
CREATE TABLE RECLAMO_EQUIPAJE (
  ID_RECLAMO      NUMBER(10)    NOT NULL,
  ID_EQUIPAJE     NUMBER(10)    NOT NULL,
  FECHA_RECLAMO   DATE          NOT NULL,
  TIPO_RECLAMO    VARCHAR2(15)  NOT NULL,
  ESTADO_RECLAMO  VARCHAR2(15)  NOT NULL,
  DESCRIPCION     VARCHAR2(300),
  CONSTRAINT PK_RECLAMO_EQUIPAJE   PRIMARY KEY (ID_RECLAMO),
  CONSTRAINT FK_RECLAMO_EQUIPAJE   FOREIGN KEY (ID_EQUIPAJE) REFERENCES EQUIPAJE (ID_EQUIPAJE),
  CONSTRAINT CK_RECLAMO_TIPO       CHECK (TIPO_RECLAMO IN ('PERDIDA','DANO')),
  CONSTRAINT CK_RECLAMO_ESTADO     CHECK (ESTADO_RECLAMO IN ('ABIERTO','EN PROCESO','RESUELTO','RECHAZADO'))
);


--------------------------------------------------------------------------------
-- BLOCK 6. OPERATIONAL EVENTS AND ALERTS
--------------------------------------------------------------------------------

-- Event log with timestamp and the reporting user.
-- Rows are never updated: a new row is always inserted.
CREATE TABLE EVENTO_OPERATIVO (
  ID_EVENTO                NUMBER(12)    NOT NULL,
  NUM_VUELO                VARCHAR2(10)  NOT NULL,
  FECHA_OPERACION          DATE          NOT NULL,
  NUM_SECUENCIA            NUMBER(2)     NOT NULL,
  TIPO_EVENTO              VARCHAR2(25)  NOT NULL,
  MARCA_TIEMPO             DATE          NOT NULL,
  MOTIVO                   VARCHAR2(20),
  COD_IATA_GATE            CHAR(3),
  TERMINAL_GATE            VARCHAR2(10),
  ID_GATE                  VARCHAR2(10),
